-- Run once in the Supabase SQL editor to enable ORACLE's shared memory.
create table if not exists public.oracle_memories (
  id bigint generated by default as identity primary key,
  content text not null check (char_length(content) <= 3000),
  source text not null default 'oracle',
  created_at timestamptz not null default now()
);
alter table public.oracle_memories enable row level security;
-- Do not add public policies. ORACLE accesses this table server-side with SUPABASE_SERVICE_ROLE_KEY.
create index if not exists oracle_memories_created_at_idx on public.oracle_memories (created_at desc);
